CREATE TABLE repayment_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL REFERENCES household(id),
    sender_member_id BIGINT NOT NULL REFERENCES member(id),
    recipient_member_id BIGINT NOT NULL REFERENCES member(id),
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0 AND amount <= 100000000.00),
    kind VARCHAR(10) NOT NULL CHECK (kind IN ('PAYMENT', 'REVERSAL')),
    correction_of_request_id BIGINT REFERENCES repayment_request(id),
    reason VARCHAR(200),
    status VARCHAR(12) NOT NULL CHECK (status IN ('PENDING', 'CONFIRMED', 'REJECTED', 'EXPIRED', 'VOID')),
    created_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    decided_at TIMESTAMP,
    expense_id BIGINT UNIQUE REFERENCES expense(id),
    source_update_id VARCHAR(128) NOT NULL UNIQUE,
    token VARCHAR(32) NOT NULL UNIQUE,
    announcement_message_id INTEGER,
    outcome_message_id INTEGER,
    announcement_attempts INTEGER NOT NULL DEFAULT 0,
    outcome_attempts INTEGER NOT NULL DEFAULT 0,
    next_announcement_at TIMESTAMP NOT NULL,
    next_outcome_at TIMESTAMP NOT NULL,
    version INTEGER NOT NULL DEFAULT 0,
    CHECK (sender_member_id <> recipient_member_id),
    CHECK ((kind = 'PAYMENT' AND correction_of_request_id IS NULL AND reason IS NULL)
        OR (kind = 'REVERSAL' AND correction_of_request_id IS NOT NULL AND reason IS NOT NULL AND expense_id IS NULL)),
    CHECK (kind <> 'PAYMENT' OR (status = 'CONFIRMED' AND expense_id IS NOT NULL)
        OR (status <> 'CONFIRMED' AND (status = 'VOID' OR expense_id IS NULL)))
);
CREATE INDEX repayment_household_status ON repayment_request(household_id, status, expires_at);
CREATE INDEX repayment_correction_target ON repayment_request(correction_of_request_id);
