-- Clean installations only. Existing complete pre-V2 schemas are baselined at version 1.
-- This migration creates the ten legacy tables and does not change financial rows.
CREATE TABLE household (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_chat_id BIGINT NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    last_digest_date DATE
);

CREATE TABLE member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL,
    telegram_user_id BIGINT NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    telegram_username VARCHAR(255),
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_member_household_telegram_user UNIQUE (household_id, telegram_user_id),
    CONSTRAINT fk_member_household FOREIGN KEY (household_id) REFERENCES household(id)
);

CREATE TABLE expense (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL,
    payer_id BIGINT NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    deleted BOOLEAN NOT NULL,
    settlement BOOLEAN NOT NULL,
    CONSTRAINT fk_expense_household FOREIGN KEY (household_id) REFERENCES household(id),
    CONSTRAINT fk_expense_payer FOREIGN KEY (payer_id) REFERENCES member(id)
);

CREATE TABLE expense_share (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_id BIGINT NOT NULL,
    member_id BIGINT NOT NULL,
    share_amount NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_share_expense FOREIGN KEY (expense_id) REFERENCES expense(id),
    CONSTRAINT fk_share_member FOREIGN KEY (member_id) REFERENCES member(id)
);

CREATE TABLE cooking_schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL,
    day_of_week VARCHAR(9) NOT NULL,
    member_id BIGINT NOT NULL,
    CONSTRAINT uk_cooking_schedule_household_day_member UNIQUE (household_id, day_of_week, member_id),
    CONSTRAINT fk_schedule_household FOREIGN KEY (household_id) REFERENCES household(id),
    CONSTRAINT fk_schedule_member FOREIGN KEY (member_id) REFERENCES member(id)
);
CREATE INDEX idx_cooking_schedule_household_day ON cooking_schedule(household_id, day_of_week);

CREATE TABLE cooking_swap (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL,
    swap_date DATE NOT NULL,
    from_member_id BIGINT NOT NULL,
    to_member_id BIGINT NOT NULL,
    CONSTRAINT uk_cooking_swap_household_date_from UNIQUE (household_id, swap_date, from_member_id),
    CONSTRAINT fk_swap_household FOREIGN KEY (household_id) REFERENCES household(id),
    CONSTRAINT fk_swap_from FOREIGN KEY (from_member_id) REFERENCES member(id),
    CONSTRAINT fk_swap_to FOREIGN KEY (to_member_id) REFERENCES member(id)
);
CREATE INDEX idx_cooking_swap_household_date ON cooking_swap(household_id, swap_date);

CREATE TABLE shopping_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL,
    text VARCHAR(60) NOT NULL,
    added_by BIGINT NOT NULL,
    added_at TIMESTAMP(6) NOT NULL,
    bought BOOLEAN NOT NULL,
    bought_by BIGINT,
    bought_at TIMESTAMP(6),
    CONSTRAINT fk_shopping_household FOREIGN KEY (household_id) REFERENCES household(id),
    CONSTRAINT fk_shopping_added_by FOREIGN KEY (added_by) REFERENCES member(id),
    CONSTRAINT fk_shopping_bought_by FOREIGN KEY (bought_by) REFERENCES member(id)
);
CREATE INDEX idx_shopping_household_bought ON shopping_item(household_id, bought);

CREATE TABLE note (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    text VARCHAR(300) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    deleted BOOLEAN NOT NULL,
    CONSTRAINT fk_note_household FOREIGN KEY (household_id) REFERENCES household(id),
    CONSTRAINT fk_note_author FOREIGN KEY (author_id) REFERENCES member(id)
);
CREATE INDEX idx_note_household ON note(household_id);

CREATE TABLE chore_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL,
    member_id BIGINT NOT NULL,
    text VARCHAR(100) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_chore_household FOREIGN KEY (household_id) REFERENCES household(id),
    CONSTRAINT fk_chore_member FOREIGN KEY (member_id) REFERENCES member(id)
);
CREATE INDEX idx_chore_household ON chore_log(household_id);

CREATE TABLE payment_deadline (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL,
    title VARCHAR(40) NOT NULL,
    day_of_month INTEGER NOT NULL,
    amount NUMERIC(12, 2),
    created_by BIGINT NOT NULL,
    active BOOLEAN NOT NULL,
    CONSTRAINT fk_deadline_household FOREIGN KEY (household_id) REFERENCES household(id),
    CONSTRAINT fk_deadline_creator FOREIGN KEY (created_by) REFERENCES member(id)
);
CREATE INDEX idx_deadline_household_active ON payment_deadline(household_id, active);
