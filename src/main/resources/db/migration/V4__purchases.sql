CREATE TABLE purchase (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT NOT NULL REFERENCES household(id),
    buyer_member_id BIGINT NOT NULL REFERENCES member(id),
    status VARCHAR(12) NOT NULL CHECK (status IN ('CONFIRMED', 'VOID')),
    shared BOOLEAN NOT NULL,
    total NUMERIC(12,2) NOT NULL CHECK (total > 0 AND total <= 100000000.00),
    purchased_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    confirmed_at TIMESTAMP NOT NULL,
    expense_id BIGINT UNIQUE REFERENCES expense(id),
    confirmation_key VARCHAR(32) NOT NULL UNIQUE,
    version INTEGER NOT NULL DEFAULT 0,
    CHECK ((shared AND expense_id IS NOT NULL) OR (NOT shared AND expense_id IS NULL))
);
CREATE INDEX purchase_household_history ON purchase(household_id, id);

CREATE TABLE purchase_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT NOT NULL REFERENCES purchase(id),
    catalog_key VARCHAR(32),
    label VARCHAR(120) NOT NULL CHECK (CHAR_LENGTH(label) BETWEEN 1 AND 60),
    price NUMERIC(12,2) NOT NULL CHECK (price > 0 AND price <= 100000000.00),
    position INTEGER NOT NULL CHECK (position BETWEEN 0 AND 19),
    UNIQUE (purchase_id, position)
);

CREATE TABLE purchase_participant (
    purchase_id BIGINT NOT NULL REFERENCES purchase(id),
    member_id BIGINT NOT NULL REFERENCES member(id),
    PRIMARY KEY (purchase_id, member_id)
);
